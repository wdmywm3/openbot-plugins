"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const { memoryDatabase } = require("./helpers/memory-database.cjs");
const sandbox = { module: { exports: {} } };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../plugins/bilibili-explorer/index.js"), "utf8"), sandbox);
(async () => {
  const notices = [], logs = [], ctx = { message: { chatId: "onebot:private:owner" }, api: {} };
  memoryDatabase(ctx);
  ctx.api.publishConversationEvent = async event => { notices.push(JSON.parse(JSON.stringify(event))); };
  ctx.api.log = async entry => logs.push(entry);
  const input = { bvid: "BV1234567890", part: 1, title: "A video", summary: "Grounded reading summary", reason: "partial coverage", sources: ["https://www.bilibili.com/video/BV1234567890"] };
  await sandbox.saveVideoNote(ctx, input, ctx.message.chatId);
  assert.equal(notices.length, 1); assert.equal(notices[0].delivery, "inject"); assert.equal(notices[0].chatId, ctx.message.chatId);
  assert.equal(JSON.parse(notices[0].text).summary, input.summary);
  await sandbox.saveVideoNote(ctx, input, ctx.message.chatId);
  assert.equal(notices[0].id, notices[1].id, "re-saving unchanged evidence has the same event id");
  await sandbox.saveVideoNote(ctx, { ...input, summary: "Updated evidence" }, ctx.message.chatId);
  assert.notEqual(notices[1].id, notices[2].id); assert.equal(notices[1].replaceKey, notices[2].replaceKey);
  await sandbox.saveVideoNote(ctx, { ...input, focused: true, question: "Q" }, ctx.message.chatId);
  await sandbox.saveVideoNote(ctx, { ...input, focused: true, question: "Q" }, ctx.message.chatId);
  assert.equal(notices[3].id, notices[4].id, "focused-reading timestamps do not change the notification identity");
  await sandbox.saveVideoNote(ctx, input, ""); assert.equal(notices.length, 5, "public notes are not copied into an arbitrary private chat");
  ctx.api.publishConversationEvent = async () => { throw new Error("host paused"); };
  await sandbox.saveVideoNote(ctx, { ...input, summary: "Saved before failed notification" }, ctx.message.chatId);
  assert.equal(logs.length, 1);
  const note = await ctx.api.database({ name: "bilibili-history", scope: "chat", chatId: ctx.message.chatId, action: "get", collection: "notes", key: "BV1234567890:p:1" });
  assert.equal(note.record.value.summary, "Saved before failed notification", "notification failure does not undo a saved reading or retry side effects");
  delete ctx.api.publishConversationEvent;
  await sandbox.saveVideoNote(ctx, input, ctx.message.chatId);
  console.log("Conversation notices: scoped inject, stable ids, pending replacement, public-note isolation and older-host/failure compatibility passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
